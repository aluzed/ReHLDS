#!/bin/bash
# Field validation server (MT-702): the fork's engine on a real, public HLDS with
# a typical plugin stack, for real players.
#
# usage:
#   server.sh setup                 copies the benchmark HLDS install, installs
#                                   Metamod-R, AMX Mod X and ReAPI
#   server.sh start [engine label] [extra server args...]
#                                   starts the server in the background
#                                   (engine: build stored by tools/bench/build.sh,
#                                   default the latest; FEATURES=0 for the
#                                   original behaviour)
#   server.sh stop
#   server.sh status                server status and network thread counters
#   server.sh rcon <command...>
#   server.sh profile <seconds>     records the frame profiler, saves the CSV
#   server.sh console               attaches to the console (detach: Ctrl-P Ctrl-Q)
#
# The server listens on UDP 27015 of the host (--network host): forward it on the
# router for players on the internet. The RCON password is generated by setup in
# .bench/staging/rcon_password.txt.
set -euo pipefail
. "$(dirname "$0")/../bench/lib/common.sh"

STAGING_DIR=$BENCH_DIR/staging
SERVER_DIR=$STAGING_DIR/hlds
CONTAINER=rehlds-staging
PORT=27015

# The fork's optimisations are on by default. FEATURES=0 starts the same build with
# all of them off (original engine behaviour) for comparison sessions.
if [ "${FEATURES:-1}" = 0 ]; then
	FEATURE_ARGS=(+sys_ticrate 1000 "${ORIGINAL_ENGINE_ARGS[@]}")
else
	FEATURE_ARGS=(+sys_ticrate 1000)
fi

rcon() {
	python3 "$(dirname "$0")/rcon.py" --server "127.0.0.1:$PORT" --password-file "$STAGING_DIR/rcon_password.txt" "$@"
}

cmd_setup() {
	[ -x "$HLDS_DIR/hlds_linux" ] || die "HLDS not installed, run tools/bench/setup.sh first"
	[ ! -e "$SERVER_DIR" ] || die "$SERVER_DIR already exists"

	cp -a "$HLDS_DIR" "$SERVER_DIR"
	local game=$SERVER_DIR/cstrike
	local downloads=$STAGING_DIR/downloads
	mkdir -p "$downloads"/{metamod,reapi,amxx}

	gh release download "$METAMOD_RELEASE" -R rehlds/Metamod-R -p 'metamod-bin-*.zip' -D "$downloads/metamod" --clobber
	gh release download "$REAPI_RELEASE" -R rehlds/ReAPI -p 'reapi-bin-*.zip' -D "$downloads/reapi" --clobber
	gh release download "$AMXX_RELEASE" -R alliedmodders/amxmodx -p '*base-linux.tar.gz' -p '*cstrike-linux.tar.gz' -D "$downloads/amxx" --clobber

	(cd "$downloads/metamod" && unzip -q -o ./*.zip -d x)
	(cd "$downloads/reapi" && unzip -q -o ./*.zip -d x)
	mkdir -p "$game/addons/metamod"
	cp "$downloads/metamod/x/addons/metamod/metamod_i386.so" "$downloads/metamod/x/addons/metamod/config.ini" "$game/addons/metamod/"
	for archive in "$downloads"/amxx/*.tar.gz; do
		tar xzf "$archive" -C "$game"
	done
	cp "$downloads/reapi/x/addons/amxmodx/modules/reapi_amxx_i386.so" "$game/addons/amxmodx/modules/"

	echo 'linux addons/amxmodx/dlls/amxmodx_mm_i386.so' > "$game/addons/metamod/plugins.ini"
	echo reapi >> "$game/addons/amxmodx/configs/modules.ini"
	sed -i 's|^gamedll_linux .*|gamedll_linux "addons/metamod/metamod_i386.so"|' "$game/liblist.gam"

	python3 -c "import secrets; print(secrets.token_urlsafe(12))" > "$STAGING_DIR/rcon_password.txt"
	chmod 600 "$STAGING_DIR/rcon_password.txt"
	log "installed in $SERVER_DIR; write $game/server.cfg (rcon_password from $STAGING_DIR/rcon_password.txt)"
}

cmd_start() {
	local label=${1:-}
	[ $# -gt 0 ] && shift
	if [ -z "$label" ]; then
		label=$(ls -t "$BENCH_DIR/engines" | head -1)
	fi
	local engine=$BENCH_DIR/engines/$label/engine_i486.so
	[ -f "$engine" ] || die "no engine build named '$label'"
	[ -d "$SERVER_DIR" ] || die "run '$0 setup' first"

	if docker ps -q --filter "name=^$CONTAINER\$" | grep -q .; then
		die "already running, '$0 stop' first"
	fi
	docker rm "$CONTAINER" > /dev/null 2>&1 || true

	cp "$engine" "$SERVER_DIR/engine_i486.so"
	echo "$label features=${FEATURES:-1} $(cat "$BENCH_DIR/engines/$label/commit.txt" 2>/dev/null)" > "$STAGING_DIR/engine.txt"

	# Core dumps go to the server directory (core_pattern permitting)
	docker run -d -it --name "$CONTAINER" --network host --ulimit core=-1 \
		-u "$(id -u):$(id -g)" -e HOME="$STEAM_HOME" -e LD_LIBRARY_PATH=. \
		-v "$BENCH_DIR:$BENCH_DIR" -w "$SERVER_DIR" \
		"$BENCH_IMAGE" ./hlds_linux -game cstrike -console -port "$PORT" +maxplayers 20 \
		"${FEATURE_ARGS[@]}" "$@" +map de_dust2 > /dev/null

	log "started engine '$label' on UDP $PORT; logs: docker logs -f $CONTAINER"
}

cmd_stop() {
	rcon quit > /dev/null 2>&1 || true
	sleep 3
	docker stop "$CONTAINER" > /dev/null 2>&1 || true
	docker rm "$CONTAINER" > /dev/null 2>&1 || true
	log "stopped"
}

cmd_profile() {
	FEATURES_RUNNING=$(sed -n 's/.*features=\([01]\).*/\1/p' "$STAGING_DIR/engine.txt" 2>/dev/null)
	local seconds=${1:-300}
	local name=profile-$(date +%Y%m%d-%H%M%S)-features${FEATURES_RUNNING:-}.csv
	# The profiler keeps the last sv_profile_frames frames: size it for the whole
	# capture at 1000 Hz (at most 600 s), sv_profile_reset applies the new size
	local frames=$((seconds * 1000 + 5000))
	[ "$frames" -gt 600000 ] && frames=600000
	rcon sv_profile_frames "$frames" > /dev/null
	rcon sv_profile_reset > /dev/null
	rcon sv_profile "$seconds"
	sleep $((seconds + 2))
	rcon sv_profile_csv "$name"
	mkdir -p "$STAGING_DIR/profiles"
	mv "$SERVER_DIR/cstrike/$name" "$STAGING_DIR/profiles/"
	rcon status
	rcon net_thread_stats
	log "saved $STAGING_DIR/profiles/$name"
}

case ${1:-} in
	setup) cmd_setup ;;
	start) shift; cmd_start "$@" ;;
	stop) cmd_stop ;;
	status) cat "$STAGING_DIR/engine.txt" 2>/dev/null; rcon status; rcon net_thread_stats ;;
	rcon) shift; rcon "$@" ;;
	profile) shift; cmd_profile "$@" ;;
	console) docker attach "$CONTAINER" ;;
	*) sed -n '2,22p' "$0"; exit 1 ;;
esac
